import { describe, it, expect } from 'vitest';
import { isStaleForWorkingDay, workingDayStart } from '../working-day';

/**
 * Граница рабочего дня — 01:00 по Берлину.
 *
 * Проверяем не «функция что-то вернула», а поведение на стыках: полночь (смена
 * ещё идёт), сам час ночи (день сменился) и обе ночи перевода часов — именно там
 * арифметика по смещению даёт промах на час, из-за которого заказы либо исчезают
 * раньше времени, либо остаются висеть лишние сутки.
 */

/** Летом Берлин = UTC+2, зимой = UTC+1. */
const iso = (s: string) => new Date(s);

describe('workingDayStart', () => {
  it('в полночь смена ещё вчерашняя', () => {
    // 00:30 по Берлину 18 августа (22:30 UTC 17-го) → день начался 17-го в 01:00.
    expect(workingDayStart(iso('2026-08-17T22:30:00Z')).toISOString()).toBe(
      '2026-08-16T23:00:00.000Z'
    );
  });

  it('в час ночи начинается новый рабочий день', () => {
    // 01:00 по Берлину 18 августа = 23:00 UTC 17-го.
    expect(workingDayStart(iso('2026-08-17T23:00:00Z')).toISOString()).toBe(
      '2026-08-17T23:00:00.000Z'
    );
  });

  it('вечер принадлежит начавшемуся дню', () => {
    // 21:00 по Берлину 18 августа → тот же день, начало 18-го в 01:00.
    expect(workingDayStart(iso('2026-08-18T19:00:00Z')).toISOString()).toBe(
      '2026-08-17T23:00:00.000Z'
    );
  });

  it('зимой смещение другое, а граница та же', () => {
    // 20:00 по Берлину 15 января (UTC+1) → начало 15-го в 01:00 = 00:00 UTC.
    expect(workingDayStart(iso('2026-01-15T19:00:00Z')).toISOString()).toBe(
      '2026-01-15T00:00:00.000Z'
    );
  });

  it('в ночь перехода на летнее время не промахивается на час', () => {
    // Перевод 29 марта 2026: 02:00 → 03:00. Вечер 29-го, день начался в 01:00,
    // ещё по зимнему смещению (UTC+1).
    expect(workingDayStart(iso('2026-03-29T18:00:00Z')).toISOString()).toBe(
      '2026-03-29T00:00:00.000Z'
    );
  });

  it('в ночь перехода на зимнее время тоже', () => {
    // Перевод 25 октября 2026: 03:00 → 02:00. Вечер 25-го уже по UTC+1,
    // а 01:00 того же дня было ещё по летнему смещению (UTC+2).
    expect(workingDayStart(iso('2026-10-25T18:00:00Z')).toISOString()).toBe(
      '2026-10-24T23:00:00.000Z'
    );
  });
});

describe('isStaleForWorkingDay', () => {
  const now = iso('2026-08-18T19:00:00Z'); // 21:00 по Берлину

  it('заказ этой смены не устарел', () => {
    expect(isStaleForWorkingDay('2026-08-18T16:47:00Z', now)).toBe(false);
  });

  it('вчерашний заказ устарел', () => {
    expect(isStaleForWorkingDay('2026-08-17T20:00:00Z', now)).toBe(true);
  });

  it('заказ, принятый вчера в 23:50, устареет только в час ночи', () => {
    const lateOrder = '2026-08-17T21:50:00Z'; // 23:50 по Берлину 17-го
    // В полночь 18-го смена та же — заказ ещё живой.
    expect(isStaleForWorkingDay(lateOrder, iso('2026-08-17T22:10:00Z'))).toBe(false);
    // В 01:10 — уже мусор.
    expect(isStaleForWorkingDay(lateOrder, iso('2026-08-17T23:10:00Z'))).toBe(true);
  });

  it('мусор во времени не считает устаревшим', () => {
    // Пустая дата не должна приводить к удалению карточки: молчаливое удаление
    // из-за кривых данных хуже, чем лишняя карточка в ленте.
    expect(isStaleForWorkingDay(null, now)).toBe(false);
    expect(isStaleForWorkingDay('не дата', now)).toBe(false);
  });
});
