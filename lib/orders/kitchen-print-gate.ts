/**
 * Когда кюхенбон ГОТОВ к печати.
 *
 * Бон раньше уходил на бумагу в первые секунды жизни заказа — до того, как
 * кухня на приёме выставила время. На чеке самовывоза поэтому стояло время
 * приёма, а не обещанный час (ABHOLZEIT печатается из `orderDueMs`, которого
 * у непринятого заказа ещё нет). Теперь автоматическая печать ждёт принятия.
 *
 * Три случая, когда заказ выдаётся печатным лентам (прибор и LAN-агент):
 *  - кухня заказ ПРИНЯЛА (любой статус после `new`, кроме `cancelled`) —
 *    обещанный час уже в заказе и попадает на бумагу;
 *  - явный повтор печати (`kitchenPrintSeq > 0`) — просьба человека сильнее
 *    любых гейтов, как и у выключателя автопечати;
 *  - заказ висит непринятым дольше грейса — печатаем как раньше: бумага
 *    остаётся резервным будильником, если прибор молчит или сломан.
 *
 * Отклонённый заказ (`cancelled` до первой печати) на бумагу не попадает
 * вовсе — чек отменённого заказа только путал сборщика.
 */

/** Сколько ждём принятия, прежде чем напечатать бон без обещанного часа. */
export const KITCHEN_PRINT_ACCEPT_GRACE_MS = 3 * 60_000;

/** Mongo-фильтр «бон готов к печати» — И-условие к остальным фильтрам ленты. */
export function kitchenPrintAcceptGate(nowMs: number) {
  return {
    $or: [
      { status: { $nin: ['new', 'cancelled'] } },
      { kitchenPrintSeq: { $gt: 0 } },
      { status: 'new', createdAt: { $lte: new Date(nowMs - KITCHEN_PRINT_ACCEPT_GRACE_MS) } },
    ],
  };
}
