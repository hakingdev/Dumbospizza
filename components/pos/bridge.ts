'use client';

/**
 * Мост в приложение-киоск (KioskActivity.TerminalBridge).
 *
 * Объявление одно на весь терминал, потому что `Window` в TypeScript
 * склеивается из всех `declare global`: два разных описания `DumboPos` в разных
 * файлах — это не «каждый про своё», а ошибка компиляции. Заодно видно одним
 * взглядом, что именно приложение обязано отдать вебу.
 *
 * Все методы необязательные: в обычном браузере моста нет вовсе, а на приборе
 * может стоять старая сборка apk, где новых методов ещё не завезли. Веб при
 * этом должен работать — просто без соответствующей кнопки.
 */
export interface PosTerminalBridge {
  /** Открыть системную панель Wi-Fi. */
  openWifiSettings?: () => void;
  /** Открыть системный выбор звука. Результат придёт событием, а не ответом. */
  pickAlertSound?: () => void;
  /** Проиграть выбранный звук. `false` значит «играть нечем» — тогда сигнал за страницей. */
  playAlert?: () => boolean | void;
  /** Оборвать звук: рингтон бывает длиннее, чем нужно. */
  stopAlert?: () => void;
  /** Имя звука для показа человеку. Пусто — звучать нечему. */
  alertSoundName?: () => string;
}

declare global {
  interface Window {
    DumboPos?: PosTerminalBridge;
  }
}

/**
 * Событие, которым приложение сообщает о новом выбранном звуке.
 *
 * Системный выбор — чужая Activity, её результат приходит в onActivityResult,
 * то есть асинхронно и уже после того, как `pickAlertSound()` вернул управление.
 * Имя события держим здесь, рядом с остальным описанием моста: разъедется оно —
 * разъедется молча, и вкладка «Mehr» будет показывать старый звук.
 */
export const POS_ALERT_SOUND_EVENT = 'dumbo-alert-sound';

/**
 * Мост, если он есть.
 *
 * Проверка на `window` нужна из-за SSR: страницы терминала рендерятся и на
 * сервере, а там обращение к `window` — падение всей страницы, а не тихий отказ.
 */
export function posBridge(): PosTerminalBridge | undefined {
  if (typeof window === 'undefined') return undefined;
  return window.DumboPos;
}
